@pytest.mark.parametrize(
    "setup", ["missing", "corrupt"], ids=["text-fallback-missing-logo",
                                          "text-fallback-corrupt-logo"])
def test_render_without_logo_uses_text_badge(tmp_path, setup):
    """Rendered PNG shows the white foreground of the text fallback on the poster.

    Reference-width poster (1000x1500, see overlay_render._REFERENCE_WIDTH):
    at the default 200px-wide fixture this element's font scales down to the
    8px floor, rendering text too small to clear the pixel threshold below --
    that would test the floor clamp, not the text fallback itself.
    """
    if setup == "corrupt":
        d = tmp_path / "logos"; d.mkdir(parents=True)
        (d / "imdb.png").write_bytes(b"not-a-png-bytes-\x00\xff")
    out = render_overlay_png(_poster(1000, 1500), IMDB_STYLE_DOC,
                             values={"rating_imdb": "8.7"}, assets_root=tmp_path)
    im = Image.open(io.BytesIO(out)).convert("RGB")
    # The plain poster has no near-white pixels; after rendering it must.
    white = [px for px in im.get_flattened_data() if min(px[:3]) > 220]
    assert len(white) > 50, "expected visible 'IMDb 8.7' text pixels on plate"


