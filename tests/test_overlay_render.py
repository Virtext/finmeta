"""Rating-logo loading for overlay rendering (SPEC S9 §D step 4).

Logos are NOT shipped anywhere in git or fixture/. The user drops their own PNGs at one of two roots:

* ``assets_root/logos/<key>.png`` — the local asset source directory
  (config ``local.path``, e.g. /config/assets inside the container), OR
* ``<config_dir>/assets/logos/<key>.png`` — fallback when only the config dir is known.

On a miss (or corrupt file) the compositor renders text instead ("IMDb 8.7") with
the element's font/colours; on a hit it scales the logo to the element size and
draws the score beside it. Every logo used below is generated by this test from PIL bytes.
"""
