def _write_pack(config_dir, pack_name="kometa"):
    """Tiny fake install of a logo pack under <config>/assets/logos/<pack>/.

    Every file is a distinct solid colour so tests can tell which badge image was
    actually drawn by counting matching pixels on the rendered output."""
    from finmeta.engine.logo_packs import load_pack
    root = Path(config_dir) / "assets" / "logos" / pack_name
    root.mkdir(parents=True, exist_ok=True)
    colors = {
        "imdb": (255, 0, 0, 255),
        "rt_fresh": (0, 180, 0, 255),
        "rt_rotten": (160, 30, 30, 255),
        "resolution": None,   # not used directly; real keys below are what get written
    }
    for key in sorted(load_pack("kometa")["files"]):
        img = Image.new("RGBA", (40, 20), (255, 255, 255, 255))
        buf = io.BytesIO(); img.save(buf, format="PNG")
        p_ = root / f"{key}.png"; p_.write_bytes(buf.getvalue())
    return root


def _count_color(img: Image.Image, color=(255, 0, 0, 255)):
    px = img.convert("RGB").get_flattened_data()
    r,g,b = color[:3]
    return sum(1 for (pr,pg,pb) in px if abs(pr-r)<10 and abs(pg-g)<10 and abs(pb-b)<10)


