def _norm_px(x):
    """Accept raw PNG/JPEG bytes or an already-opened PIL image; return RGB pixels as a flat tuple."""
    if isinstance(x, Image.Image):
        x = x.convert("RGB")
    else:
        x = Image.open(io.BytesIO(x)).convert("RGB")
    return x.get_flattened_data()


def _pixel_diff(a, b) -> int:
    ta, tb = _norm_px(a), _norm_px(b)
    assert len(ta) == len(tb), f"size mismatch {len(ta)} vs {len(tb)}"
    return sum(1 for pa, pb in zip(ta, tb) if pa != pb)


