def test_logo_packs_priority_order_first_match_wins(tmp_path):
    from finmeta.engine.overlay_render import render_overlay_png
    cfg_dir = tmp_path / "config"
    # two packs both have an imdb image in distinct colours; list order decides.
    d1 = Path(cfg_dir) / "assets" / "logos" / "custom"; d1.mkdir(parents=True, exist_ok=True)
    d2 = Path(cfg_dir) / "assets" / "logos" / "kometa"; d2.mkdir(parents=True, exist_ok=True)
    def write(d_, key, rgb):
        img = Image.new("RGBA", (40, 20), rgb + (255,)); buf = io.BytesIO(); img.save(buf, format="PNG")
        (d_ / f"{key}.png").write_bytes(buf.getvalue())
    # custom pack: flat layout <root>/logos/<key>.png — write under a fake "custom" dir AND flat
    write(d1, "imdb", (0, 0, 255))                       # blue via custom subfolder
    (Path(cfg_dir) / "assets" / "logos" / "imdb.png").parent.mkdir(parents=True, exist_ok=True)
    write(Path(cfg_dir) / "assets" / "logos", "imdb", (0, 255, 0))  # green flat layout = custom source
    write(d2, "imdb", (255, 0, 0))                       # red kometa
    doc = {"elements": {"imdb": {"enabled": True}}}
    vals = {"rating_imdb": "8.7"}
    out_first = Image.open(io.BytesIO(render_overlay_png(
        _poster(), doc, values=vals, config_dir=cfg_dir, logo_pack=["custom", "kometa"]))).convert("RGB")
    assert _count_color(out_first, (0, 255, 0)) > 10     # custom (green) wins over kometa
    out_second = Image.open(io.BytesIO(render_overlay_png(
        _poster(), doc, values=vals, config_dir=cfg_dir, logo_pack=["kometa", "custom"]))).convert("RGB")
    assert _count_color(out_second, (255, 0, 0)) > 10    # kometa (red) wins when listed first
    # legacy single-string still works
    out_legacy = Image.open(io.BytesIO(render_overlay_png(
        _poster(), doc, values=vals, config_dir=cfg_dir, logo_pack="kometa"))).convert("RGB")
    assert _count_color(out_legacy, (255, 0, 0)) > 10


