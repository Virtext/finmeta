# ---------------------------------------------------------------- helpers --

def _poster(width=200, height=300) -> bytes:
    img = Image.new("RGB", (width, height), (30, 40, 90))
    buf = io.BytesIO(); img.save(buf, format="JPEG")
    return buf.getvalue()


LOGO_COLOR = (255, 170, 0, 255)


def _write_logo(root: Path, key: str = "imdb") -> Path:
    """Fixture-generated logo PNG (never shipped): solid orange square."""
    d = root / "logos"; d.mkdir(parents=True, exist_ok=True)
    p = d / f"{key}.png"
    img = Image.new("RGBA", (96, 48), LOGO_COLOR)
    buf = io.BytesIO(); img.save(buf, format="PNG")
    p.write_bytes(buf.getvalue())
    return p


IMDB_STYLE_DOC = {
    "base_position": "bottom_left", "margin": 24, "font_size": 34,
    "bg": "#000000B0", "fg": "#FFFFFF", "radius": 12,
    "elements": {"imdb": {"enabled": True}},
}

from finmeta.engine.style_presets import (
    ELEMENT_KEYS as ELEMENT_KEYS_ALL, ElementStyle, OverlayStyleDoc,
)  # noqa: E402

DOC = OverlayStyleDoc(**IMDB_STYLE_DOC)


