def _build_ctx(cfg_dir: Path, poster_root: Path, logo_assets_root: Path | None,
               monkeypatch) -> AppContext:
    """Build an AppContext with auth off and a config.yml already on disk."""
    from finmeta.sources.candidate import Candidate
    monkeypatch.setenv("JELLYFIN_API_KEY", "fake-key")
    monkeypatch.setenv("TMDB_KEY", "fake-tmdb-key")
    monkeypatch.setenv("FINMETA_AUTH", "off")
    cfg_dir.mkdir(parents=True, exist_ok=True)
    extra = [] if logo_assets_root is None else [
        "sources:",
        "  local:",
        "    enabled: true",
        f"    path: {logo_assets_root}",
    ]
    lines = [ln.replace("{poster_root}", str(poster_root)) for ln in _CONFIG_LINES] + extra
    (cfg_dir / "config.yml").write_text("\n".join(lines) + "\n")

    def provider(item, cfg, jf, tmdb, sources, mapper):
        raw = str(getattr(item, "id", "")) or "a"
        idx = (ord(raw[-1]) % 4) + 1 if raw else 1
        ref = poster_root / f"poster{idx}.jpg"
        by_kind = {"poster": [Candidate(kind="poster", source="local", ref=str(ref),
                                        lang=None, width=200, height=300, score=0.9)]}
        return by_kind, 7

    ctx = AppContext(
        str(cfg_dir / "config.yml"), config_dir=str(cfg_dir),
        db_path=str(cfg_dir / "jobs.db"), overrides_path=str(cfg_dir / "overrides.db"),
        plan_builder=lambda *a, **k: None, candidates_provider=provider)
    ctx.make_jellyfin = lambda cfg=None: _FakeJF()
    return ctx


