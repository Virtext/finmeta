def test_rt_badge_uses_state_logo_with_text_fallback(tmp_path):
    """The RT badge picks rt_fresh.png / rt_rotten.png by state; a missing logo
    (trademarks are NOT shipped) falls back to the text pill "RT critic 87%"."""
    from finmeta.engine.overlay_render import _collect_placed, render_overlay_png
    from finmeta.engine.style_presets import OverlayStyleDoc

    doc = OverlayStyleDoc(elements={"rt_critic": {"enabled": True}})
    # Fresh state with a user-dropped logo present.
    logos = tmp_path / "logos"; logos.mkdir()
    for key, rgb in (("rt_fresh", (0, 255, 0)), ("rt_rotten", (255, 0, 0))):
        img = Image.new("RGBA", (40, 20), rgb + (255,))
        buf = io.BytesIO(); img.save(buf, format="PNG")
        (logos / f"{key}.png").write_bytes(buf.getvalue())

    def _count(rgb):
        out = Image.open(io.BytesIO(png)).convert("RGB")
        return sum(1 for px in out.get_flattened_data() if px == rgb)

    png = render_overlay_png(_poster(), doc.model_dump(), values={"rating_rt_critic": "87%"},
                             assets_root=tmp_path, logo_pack="custom")
    assert _count((0, 255, 0)) > 10, "fresh logo pixels expected"

    png = render_overlay_png(_poster(), doc.model_dump(), values={"rating_rt_critic": "43%"},
                             assets_root=tmp_path, logo_pack="custom")
